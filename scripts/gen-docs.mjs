#!/usr/bin/env node
// The fact blocks of the standards, generated from their sources (krizaka/.github#351). The prose of a standard is written;
// every FACT sits between `<!-- gen:<name>:start -->` and `<!-- gen:<name>:end -->` and is written by this script from the
// real source, so it cannot go stale:
//
//   node scripts/gen-docs.mjs              rewrite the blocks (offline sources: the workflows, guard-paths.json)
//   node scripts/gen-docs.mjs --remote     also the blocks read from GitHub (rulesets, branch protection) and npm
//   node scripts/gen-docs.mjs --check      « docs are current »: exit 1 when a block differs (never writes)
//
// An offline block is checked on every pull request (the `docs` suite of ci-gate.yml). A remote block depends on something
// outside the repository, so it is only regenerated by `--remote` (the scheduled workflow docs-current.yml, which opens a pull
// request when one changed); a remote read that fails (no admin right, 404, offline) keeps the block as it is and warns.
// GH_TOKEN / GITHUB_TOKEN is read by `gh api`; nothing is ever printed from it.
import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { pathToFileURL } from "node:url";

const ROOT = new URL("../", import.meta.url);
const read = (path) => readFileSync(new URL(path, ROOT), "utf8");

/** The text between a block's markers (without the marker lines), or null when the block is absent. */
export function blockOf(text, name) {
  const m = new RegExp(`<!-- gen:${name}:start -->\\n([\\s\\S]*?)<!-- gen:${name}:end -->`).exec(text);
  return m ? m[1] : null;
}

/** The text with the block replaced by `body` (a markdown string, no trailing blank line). Throws when the markers are missing. */
export function withBlock(text, name, body) {
  if (blockOf(text, name) === null) throw new Error(`gen:${name} markers are missing`);
  const re = new RegExp(`(<!-- gen:${name}:start -->\\n)[\\s\\S]*?(<!-- gen:${name}:end -->)`);
  return text.replace(re, (_, start, end) => `${start}${body.replace(/\n*$/, "\n")}${end}`);
}

const cell = (value) => String(value).replace(/\|/g, "\\|").replace(/\n/g, " ");
const table = (head, rows) =>
  [`| ${head.join(" | ")} |`, `| ${head.map(() => ":---").join(" | ")} |`, ...rows.map((r) => `| ${r.map(cell).join(" | ")} |`)].join("\n");

// ── sources: the shared workflows ──────────────────────────────────────────────────────────────────────────────────────

/** The jobs of a workflow file, in order: { id, name, needs[] } (top-level `jobs:` entries, two-space indented). */
export function workflowJobs(src) {
  const body = src.slice(src.indexOf("\njobs:\n") + 6);
  const jobs = [];
  let current = null;
  for (const line of body.split("\n")) {
    const id = /^ {2}([a-z][\w-]*):\s*(?:#.*)?$/.exec(line);
    if (id) {
      current = { id: id[1], name: "", needs: [] };
      jobs.push(current);
      continue;
    }
    if (!current) continue;
    const name = /^ {4}name:\s*(.+?)\s*$/.exec(line);
    if (name && !current.name) current.name = name[1].replace(/^["']|["']$/g, "");
    const needs = /^ {4}needs:\s*(.+?)\s*$/.exec(line);
    if (needs) current.needs = needs[1].replace(/^\[|\]$/g, "").split(",").map((n) => n.trim()).filter(Boolean);
  }
  return jobs;
}

/** The reusable workflows whose jobs are listed, with the sentence that says whom each one serves. */
export const SHARED = [
  ["node-ci.yml", "Next.js, Node, monorepos"],
  ["java-ci.yml", "Maven, Orazaka services (workspace flow)"],
  ["maven.yml", "JVM repositories published to Maven Central"],
  ["expo-ci.yml", "Expo apps"],
  ["python-ci.yml", "workers, scripts"],
];

export function ciJobs(readFile = read) {
  const rows = [];
  for (const [file, serves] of SHARED) {
    for (const job of workflowJobs(readFile(`.github/workflows/${file}`))) {
      const name = job.name.includes("${{") ? "one check per matrix leg" : job.name || "—";
      rows.push([`\`${file}\``, serves, `\`${job.id}\``, name, job.needs.length ? job.needs.map((n) => `\`${n}\``).join(", ") : "—"]);
    }
  }
  return `${table(["Workflow", "For", "Job", "Name (the check)", "Needs"], rows)}\n`;
}

// ── sources: guard-paths.json ──────────────────────────────────────────────────────────────────────────────────────────

export function guardPaths(readFile = read) {
  const g = JSON.parse(readFile("docs/standards/guard-paths.json"));
  const code = (list) => list.map((p) => `\`${p}\``).join(", ");
  const rows = Object.entries(g.guards).map(([kind, globs]) => [kind, code(globs)]);
  return [
    `A \`fix\` PR is one whose title matches \`${g.titlePattern}\` (branches ${code(g.skipBranches)} are skipped); the exemption is the label \`${g.exemptLabel}\` and a line matching \`${g.exemptionLine}\`. What counts as a guard:`,
    "",
    table(["Kind", "Paths"], rows),
    "",
    `A \`package.json\` that lowers a cap matching \`${g.lintCaps.pattern}\` counts too.`,
  ].join("\n") + "\n";
}

// ── sources: GitHub (rulesets and branch protection) and npm ────────────────────────────────────────────────────────────

/** `gh api <path>` as JSON, or null when it fails (404, 403, offline): a remote block then keeps its text. */
export function ghApi(path) {
  try {
    return JSON.parse(execFileSync("gh", ["api", path], { encoding: "utf8", stdio: ["ignore", "pipe", "ignore"] }));
  } catch {
    return null;
  }
}

/** The repositories to describe: the registry's, not archived, with a default branch protected or not. */
export function registryRepos(readFile = read) {
  return JSON.parse(readFile("repos.json")).repositories.filter((r) => !r.archived && r.visibility === "public").map((r) => r.name);
}

/** { repo, checks[], strict, queue } for each repository whose protection can be read; null when nothing could be read. */
export function protection(repos, api = ghApi) {
  const out = [];
  for (const repo of repos) {
    const required = api(`repos/krizaka/${repo}/branches/main/protection/required_status_checks`);
    const rulesets = api(`repos/krizaka/${repo}/rulesets`);
    if (!required && !rulesets) continue;
    out.push({
      repo,
      checks: required?.contexts ?? [],
      strict: required ? Boolean(required.strict) : null,
      queue: rulesets ? rulesets.some((r) => r.name === "Merge queue") : null,
    });
  }
  return out.length ? out : null;
}

const yn = (v) => (v === null ? "?" : v ? "yes" : "no");

export function requiredChecks(data) {
  const rows = data.map((d) => [`\`${d.repo}\``, d.checks.length ? d.checks.map((c) => `\`${c}\``).join(", ") : "—", yn(d.strict), yn(d.queue)]);
  return `${table(["Repository", "Required checks on main", "Strict", "Merge queue"], rows)}\n`;
}

export function queueState(data) {
  const on = data.filter((d) => d.queue).map((d) => `\`${d.repo}\``);
  const off = data.filter((d) => d.queue === false).map((d) => `\`${d.repo}\``);
  return [`- **On the merge queue (${on.length}):** ${on.join(", ") || "none"}.`, `- **Not on the merge queue yet (${off.length}; the Strict column of the table above says which keep strict up-to-date branches):** ${off.join(", ") || "none"}.`].join("\n") + "\n";
}

/** The version `latest` of the npm packages the standards name. */
export const NPM_PACKAGES = ["config", "ui", "query", "i18n", "tokens", "tailwind", "icons", "fonts", "charts", "email"];

export function npmLatest(name, fetchJson) {
  const j = fetchJson(`https://registry.npmjs.org/@krizaka/${name}/latest`);
  return j?.version ? { name: `@krizaka/${name}`, version: j.version, json: j } : null;
}

export function npmVersions(rows) {
  return `${table(["Package", "Latest"], rows.map((r) => [`\`${r.name}\``, r.version]))}\n`;
}

/** What `@krizaka/config` ships, read from its latest package.json: the bins and the sub-path exports. */
export function configExports(pkg) {
  const bins = Object.keys(pkg.bin ?? {}).sort();
  const exports = Object.keys(pkg.exports ?? {}).filter((k) => k !== "./package.json").sort();
  return [
    `\`@krizaka/config\` ${pkg.version} ships ${bins.length} command${bins.length === 1 ? "" : "s"} (${bins.map((b) => `\`${b}\``).join(", ") || "none"}) and ${exports.length} entry point${exports.length === 1 ? "" : "s"}: ${exports.map((e) => `\`${e}\``).join(", ") || "none"}.`,
  ].join("\n") + "\n";
}

function fetchJsonSync(url) {
  try {
    return JSON.parse(execFileSync("curl", ["-fsS", "--max-time", "20", url], { encoding: "utf8", stdio: ["ignore", "pipe", "ignore"] }));
  } catch {
    return null;
  }
}

// ── the blocks ──────────────────────────────────────────────────────────────────────────────────────────────────────────

/** { file, name, remote, render(ctx) -> string | null }: null means « could not be read, keep the block ». */
export const BLOCKS = [
  { file: "docs/standards/ci-and-deploy.md", name: "ci-jobs", remote: false, render: () => ciJobs() },
  { file: "docs/standards/ci-and-deploy.md", name: "required-checks", remote: true, render: (c) => (c.protection() ? requiredChecks(c.protection()) : null) },
  {
    file: "docs/standards/ci-and-deploy.md",
    name: "versions",
    remote: true,
    render: (c) => {
      const rows = NPM_PACKAGES.map((n) => c.npm(n));
      return rows.every(Boolean) ? npmVersions(rows) : null;
    },
  },
  { file: "docs/standards/guards.md", name: "queue-state", remote: true, render: (c) => (c.protection() ? queueState(c.protection()) : null) },
  { file: "docs/standards/guards.md", name: "guard-paths", remote: false, render: () => guardPaths() },
  { file: "docs/standards/guards.md", name: "config-exports", remote: true, render: (c) => (c.npm("config") ? configExports(c.npm("config").json) : null) },
];

/** Lazily read, once per run, the remote sources. */
export function remoteContext(api = ghApi, fetchJson = fetchJsonSync, repos = registryRepos) {
  let prot;
  const cache = new Map();
  return {
    protection: () => (prot === undefined ? (prot = protection(repos(), api)) : prot),
    npm: (name) => (cache.has(name) ? cache.get(name) : (cache.set(name, npmLatest(name, fetchJson)), cache.get(name))),
  };
}

/**
 * Renders every block against `files` ({ path: text }); returns { files: updated texts, changed: [name], skipped: [name] }.
 * `remote: false` leaves the remote blocks untouched.
 */
export function regenerate(files, { remote = false, ctx = remoteContext(), blocks = BLOCKS } = {}) {
  const out = { ...files };
  const changed = [];
  const skipped = [];
  for (const b of blocks) {
    if (b.remote && !remote) continue;
    const body = b.render(ctx);
    if (body === null) {
      skipped.push(b.name);
      continue;
    }
    const next = withBlock(out[b.file], b.name, body);
    if (next !== out[b.file]) changed.push(b.name);
    out[b.file] = next;
  }
  return { files: out, changed, skipped };
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? "").href) {
  const args = process.argv.slice(2);
  const check = args.includes("--check");
  const remote = args.includes("--remote");
  const paths = [...new Set(BLOCKS.map((b) => b.file))];
  const files = Object.fromEntries(paths.map((p) => [p, read(p)]));
  const { files: next, changed, skipped } = regenerate(files, { remote });
  for (const s of skipped) console.log(`::warning::gen:${s} could not be read from its source: the block is kept as it is`);
  if (check) {
    if (changed.length) {
      console.log(`::error::docs are not current: ${changed.join(", ")}. Run \`node scripts/gen-docs.mjs\` and commit (never hand-edit a gen block).`);
      process.exit(1);
    }
    console.log("docs are current");
  } else {
    for (const p of paths) if (next[p] !== files[p] && existsSync(new URL(p, ROOT))) writeFileSync(new URL(p, ROOT), next[p]);
    console.log(changed.length ? `updated: ${changed.join(", ")}` : "nothing to update");
  }
}
