#!/usr/bin/env node
// Regenerates the products section of profile/README.md (between the `products:start` / `products:end` markers) from
// `@krizaka/ui/sites` — the family's single list of sites — and profile/knowhow.json (the words). A new product in the
// package appears here without anyone remembering. Nothing else of the README is touched.
//
//   node scripts/profile-products.mjs            # rewrite the section
//   node scripts/profile-products.mjs --check    # exit 1 when the README is out of date
//
// SITES_MODULE overrides the path of the installed `@krizaka/ui` sites module (default: .sites/node_modules/…).
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

export const START = "<!-- products:start — generated by scripts/profile-products.mjs from @krizaka/ui/sites; do not edit -->";
export const END = "<!-- products:end -->";
export const MARKS_CDN = "https://krizaka-assets.b-cdn.net/brand";
const STATUS = { released: "Available", upcoming: "Coming soon", construction: "Under construction", development: "In development" };

/** The products to show, in reading order: the sites of kind `product`, plus the `fallback` ones the package does not know yet. */
export function collectProducts({ sites, descriptions = {}, knowhow }) {
  const byId = new Map();
  for (const s of sites) if (s.kind === "product") byId.set(s.id, { ...s, known: true });
  for (const [id, k] of Object.entries(knowhow.products)) {
    if (!byId.has(id) && k.fallback) byId.set(id, { id, kind: "product", host: k.fallback.url.replace(/^https?:\/\//, ""), ...k.fallback, known: false });
  }
  const rank = (id) => {
    const i = knowhow.order.indexOf(id);
    return i < 0 ? knowhow.order.length : i;
  };
  return [...byId.values()]
    .sort((a, b) => rank(a.id) - rank(b.id))
    .map((p) => {
      const k = knowhow.products[p.id] ?? {};
      return {
        id: p.id,
        name: p.name,
        url: p.url,
        repo: p.repo,
        knowhow: k.knowhow,
        line: k.proof ?? descriptions[p.id] ?? "",
        status: k.statusLabels?.[p.status] ?? STATUS[p.status] ?? p.status,
      };
    });
}

// GitHub serves README images through its camo cache, keyed by URL: a mark redrawn under the same URL keeps showing the
// old drawing. Each URL therefore carries the first 10 hex of the SVG's SHA-256, so it changes exactly when the mark does.
const markUrl = (id, theme, v) => `${MARKS_CDN}/${id}/mark-${theme}.svg${v ? `?v=${v}` : ""}`;

/** Markdown of the section. `marks` / `repos` say which mark and repository exist (a missing one is left out, never a dead link). */
export function renderProducts(products, { marks = () => true, repos = () => true, versions = () => "" } = {}) {
  const rows = products.map((p) => {
    const id = marks(p.id) ? p.id : "krizaka";
    const mark = `<picture><source media="(prefers-color-scheme: dark)" srcset="${markUrl(id, "dark", versions(id, "dark"))}"><img src="${markUrl(id, "light", versions(id, "light"))}" alt="${p.name}" width="48"></picture>`;
    const head = p.knowhow ? `**${p.name}** · ${p.knowhow}` : `**${p.name}**`;
    // A product without a site of its own (its url is its repository) shows the repository link once.
    const links = p.url === p.repo ? [] : [`[${p.url.replace(/^https?:\/\//, "")}](${p.url})`];
    if (p.repo && repos(p.repo)) links.push(`[Repository](${p.repo})`);
    else if (!links.length) links.push(`[${p.url.replace(/^https?:\/\//, "")}](${p.url})`);
    return `<tr><td valign="top" width="64">${mark}</td><td valign="top">\n\n${head} &nbsp;<sup>${p.status}</sup><br>${p.line}<br>${links.join(" · ")}\n\n</td></tr>`;
  });
  return `${START}\n<table>\n${rows.join("\n")}\n</table>\n${END}`;
}

export function replaceBlock(readme, block) {
  const a = readme.indexOf("<!-- products:start");
  const b = readme.indexOf(END);
  if (a < 0 || b < 0 || b < a) throw new Error("profile/README.md has no products:start / products:end markers");
  return readme.slice(0, a) + block + readme.slice(b + END.length);
}

const exists = async (url, fetchImpl) => {
  try {
    const r = await fetchImpl(url, { method: "HEAD", redirect: "follow" });
    return r.ok;
  } catch {
    return false;
  }
};

async function main() {
  const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
  const sitesPath = process.env.SITES_MODULE ?? resolve(root, ".sites/node_modules/@krizaka/ui/dist/sites.js");
  const { sites, familyLabels } = await import(pathToFileURL(sitesPath).href);
  const knowhow = JSON.parse(readFileSync(resolve(root, "profile/knowhow.json"), "utf8"));
  const products = collectProducts({ sites, descriptions: familyLabels.en.descriptions, knowhow });
  const okMarks = new Set();
  const hashes = new Map();
  const fingerprint = async (id, theme) => {
    try {
      const r = await fetch(markUrl(id, theme), { redirect: "follow" });
      if (!r.ok) return "";
      return createHash("sha256").update(Buffer.from(await r.arrayBuffer())).digest("hex").slice(0, 10);
    } catch {
      return "";
    }
  };
  for (const id of ["krizaka", ...products.map((p) => p.id)]) {
    for (const theme of ["dark", "light"]) hashes.set(`${id}/${theme}`, await fingerprint(id, theme));
    if (id !== "krizaka" && hashes.get(`${id}/dark`)) okMarks.add(id);
  }
  const okRepos = new Set();
  for (const p of products) if (p.repo && (await exists(p.repo, fetch))) okRepos.add(p.repo);
  const block = renderProducts(products, { marks: (id) => okMarks.has(id), repos: (r) => okRepos.has(r), versions: (id, theme) => hashes.get(`${id}/${theme}`) ?? "" });
  const file = resolve(root, "profile/README.md");
  const current = readFileSync(file, "utf8");
  const next = replaceBlock(current, block);
  if (process.argv.includes("--check")) {
    if (next !== current) {
      console.error("profile/README.md is out of date: run `node scripts/profile-products.mjs`");
      process.exit(1);
    }
    return;
  }
  if (next !== current) writeFileSync(file, next);
  console.log(next === current ? "profile/README.md already up to date" : `profile/README.md updated (${products.length} products)`);
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? "").href) await main();
